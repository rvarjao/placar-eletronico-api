-- Execute uma vez no SQL Editor do Supabase, antes de configurar o Flask.
create table if not exists public.placares (
  id bigint generated by default as identity primary key,
  nome_equipe_a text not null check (length(trim(nome_equipe_a)) > 0),
  nome_equipe_b text not null check (length(trim(nome_equipe_b)) > 0),
  modalidade text not null check (length(trim(modalidade)) > 0),
  status text not null default 'aguardando' check (status in ('aguardando','em_andamento','encerrado')),
  pontos_a integer not null default 0 check (pontos_a >= 0),
  pontos_b integer not null default 0 check (pontos_b >= 0),
  tempo_partida integer not null default 0 check (tempo_partida >= 0)
);
create table if not exists public.grupos (
  id bigint generated by default as identity primary key,
  nome text not null,
  turma text,
  ativo integer not null default 1 check (ativo in (0,1)),
  criado_em timestamptz not null default now()
);
alter table public.grupos add column if not exists descricao text;
alter table public.grupos add column if not exists url text
  check (url is null or url ~* '^https?://');
-- Integrantes: cada um é um registro próprio (id) pertencente a um grupo (1:N).
create table if not exists public.integrantes (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null references public.grupos(id) on delete cascade,
  nome text not null check (length(trim(nome)) > 0),
  criado_em timestamptz not null default now()
);
create index if not exists idx_integrantes_grupo on public.integrantes(grupo_id);

alter table public.integrantes enable row level security;
revoke all on public.integrantes from anon, authenticated;
grant select, insert, update, delete on public.integrantes to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Define os integrantes de um grupo em uma única transação.
-- Quem já está no grupo (mesmo nome, sem diferenciar maiúsculas) mantém o id;
-- nomes novos geram novos integrantes; quem saiu da lista é removido.
create or replace function public.definir_integrantes_grupo(p_grupo_id bigint, p_nomes text[])
returns void language plpgsql security invoker set search_path = '' as $$
declare
  v_nome text;
  v_id bigint;
  v_manter bigint[] := '{}';
begin
  foreach v_nome in array coalesce(p_nomes, '{}') loop
    v_nome := trim(v_nome);
    continue when v_nome = '';
    select id into v_id
    from public.integrantes
    where grupo_id = p_grupo_id
      and lower(nome) = lower(v_nome)
      and id <> all (v_manter)
    order by id
    limit 1;
    if v_id is null then
      insert into public.integrantes (grupo_id, nome) values (p_grupo_id, v_nome) returning id into v_id;
    else
      update public.integrantes set nome = v_nome where id = v_id and nome <> v_nome;
    end if;
    v_manter := v_manter || v_id;
  end loop;

  delete from public.integrantes where grupo_id = p_grupo_id and id <> all (v_manter);
end $$;
revoke all on function public.definir_integrantes_grupo(bigint, text[]) from public, anon, authenticated;
grant execute on function public.definir_integrantes_grupo(bigint, text[]) to service_role;
create table if not exists public.tokens_api (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null references public.grupos(id),
  token_hash text not null unique,
  prefixo text not null,
  ativo integer not null default 1 check (ativo in (0,1)),
  criado_em timestamptz not null default now(),
  revogado_em timestamptz
);
create table if not exists public.requisicoes_api (
  id bigint generated by default as identity primary key,
  grupo_id bigint references public.grupos(id),
  metodo text not null,
  rota text not null,
  status integer not null,
  duracao_ms integer not null,
  criado_em timestamptz not null default now()
);
-- Nullable: listagens e chamadas sem placar não possuem vínculo.
-- ALTER funciona tanto em instalações novas quanto nas que já executaram o schema.
alter table public.requisicoes_api
  add column if not exists placar_id bigint references public.placares(id) on delete set null;
