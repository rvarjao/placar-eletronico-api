-- Após importar IDs explícitos de SQLite/JSON, reajuste as sequências:
create or replace function public.sincronizar_ids_api_completa()
returns void language plpgsql security invoker set search_path = '' as $$
begin
  perform setval(pg_get_serial_sequence('public.placares','id'),coalesce((select max(id) from public.placares),1),exists(select 1 from public.placares));
  perform setval(pg_get_serial_sequence('public.grupos','id'),coalesce((select max(id) from public.grupos),1),exists(select 1 from public.grupos));
  perform setval(pg_get_serial_sequence('public.tokens_api','id'),coalesce((select max(id) from public.tokens_api),1),exists(select 1 from public.tokens_api));
  perform setval(pg_get_serial_sequence('public.requisicoes_api','id'),coalesce((select max(id) from public.requisicoes_api),1),exists(select 1 from public.requisicoes_api));
end $$;
revoke all on function public.sincronizar_ids_api_completa() from public, anon, authenticated;
grant execute on function public.sincronizar_ids_api_completa() to service_role;
