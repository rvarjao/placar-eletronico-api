-- Execute uma vez no SQL Editor do Supabase, antes de configurar o Flask.
create table if not exists public.placares (
  id bigint generated by default as identity primary key,
  nome_equipe_a text not null check (length(trim(nome_equipe_a)) > 0),
  nome_equipe_b text not null check (length(trim(nome_equipe_b)) > 0),
  modalidade text not null check (length(trim(modalidade)) > 0),
  status text not null default 'aguardando' check (status in ('aguardando','em_andamento','encerrado')),
  pontos_a integer not null default 0 check (pontos_a >= 0),
  pontos_b integer not null default 0 check (pontos_b >= 0),
  tempo_partida integer not null default 0 check (tempo_partida >= 0)
);
create table if not exists public.grupos (
  id bigint generated by default as identity primary key,
  nome text not null,
  turma text,
  ativo integer not null default 1 check (ativo in (0,1)),
  criado_em timestamptz not null default now()
);
create table if not exists public.tokens_api (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null references public.grupos(id),
  token_hash text not null unique,
  prefixo text not null,
  ativo integer not null default 1 check (ativo in (0,1)),
  criado_em timestamptz not null default now(),
  revogado_em timestamptz
);
create table if not exists public.requisicoes_api (
  id bigint generated by default as identity primary key,
  grupo_id bigint references public.grupos(id),
  metodo text not null,
  rota text not null,
  status integer not null,
  duracao_ms integer not null,
  criado_em timestamptz not null default now()
);
-- Nullable: listagens e chamadas sem placar não possuem vínculo.
-- ALTER funciona tanto em instalações novas quanto nas que já executaram o schema.
alter table public.requisicoes_api
  add column if not exists placar_id bigint references public.placares(id) on delete set null;
-- Estado adicional do Campeonato, Placar Eletrônico e configuração de conexão.
-- JSONB é um tipo PostgreSQL: não cria arquivos JSON no servidor.
create table if not exists public.estado_aplicacoes (
  chave text primary key,
  dados jsonb not null default '{}'::jsonb,
  atualizado_em timestamptz not null default now()
);
alter table public.estado_aplicacoes enable row level security;
revoke all on public.estado_aplicacoes from anon, authenticated;
grant select, insert, update, delete on public.estado_aplicacoes to service_role;

create index if not exists idx_requisicoes_placar_data on public.requisicoes_api(placar_id, criado_em desc);
create index if not exists idx_requisicoes_grupo_data on public.requisicoes_api(grupo_id,criado_em desc);
create index if not exists idx_requisicoes_data on public.requisicoes_api(criado_em desc);
create index if not exists idx_tokens_hash on public.tokens_api(token_hash) where ativo=1;
-- Todos os dados são privados; apenas Flask (com secret key no servidor) pode acessar.
alter table public.placares enable row level security;
alter table public.grupos enable row level security;
alter table public.tokens_api enable row level security;
alter table public.requisicoes_api enable row level security;
revoke all on public.placares, public.grupos, public.tokens_api, public.requisicoes_api from anon, authenticated;
grant select, insert, update, delete on public.placares, public.grupos, public.tokens_api, public.requisicoes_api to service_role;
grant usage, select on all sequences in schema public to service_role;
-- Após importar IDs explícitos de SQLite/JSON, reajuste as sequências:
create or replace function public.sincronizar_ids_api_completa()
returns void language plpgsql security invoker set search_path = '' as $$
begin
  perform setval(pg_get_serial_sequence('public.placares','id'),coalesce((select max(id) from public.placares),1),exists(select 1 from public.placares));
  perform setval(pg_get_serial_sequence('public.grupos','id'),coalesce((select max(id) from public.grupos),1),exists(select 1 from public.grupos));
  perform setval(pg_get_serial_sequence('public.tokens_api','id'),coalesce((select max(id) from public.tokens_api),1),exists(select 1 from public.tokens_api));
  perform setval(pg_get_serial_sequence('public.requisicoes_api','id'),coalesce((select max(id) from public.requisicoes_api),1),exists(select 1 from public.requisicoes_api));
end $$;
revoke all on function public.sincronizar_ids_api_completa() from public, anon, authenticated;
grant execute on function public.sincronizar_ids_api_completa() to service_role;
