-- Integrantes: cada um é um registro próprio (id) pertencente a um grupo (1:N).
create table if not exists public.integrantes (
  id bigint generated by default as identity primary key,
  grupo_id bigint not null references public.grupos(id) on delete cascade,
  nome text not null check (length(trim(nome)) > 0),
  criado_em timestamptz not null default now()
);
create index if not exists idx_integrantes_grupo on public.integrantes(grupo_id);

alter table public.integrantes enable row level security;
revoke all on public.integrantes from anon, authenticated;
grant select, insert, update, delete on public.integrantes to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Define os integrantes de um grupo em uma única transação.
-- Quem já está no grupo (mesmo nome, sem diferenciar maiúsculas) mantém o id;
-- nomes novos geram novos integrantes; quem saiu da lista é removido.
create or replace function public.definir_integrantes_grupo(p_grupo_id bigint, p_nomes text[])
returns void language plpgsql security invoker set search_path = '' as $$
declare
  v_nome text;
  v_id bigint;
  v_manter bigint[] := '{}';
begin
  foreach v_nome in array coalesce(p_nomes, '{}') loop
    v_nome := trim(v_nome);
    continue when v_nome = '';
    select id into v_id
    from public.integrantes
    where grupo_id = p_grupo_id
      and lower(nome) = lower(v_nome)
      and id <> all (v_manter)
    order by id
    limit 1;
    if v_id is null then
      insert into public.integrantes (grupo_id, nome) values (p_grupo_id, v_nome) returning id into v_id;
    else
      update public.integrantes set nome = v_nome where id = v_id and nome <> v_nome;
    end if;
    v_manter := v_manter || v_id;
  end loop;

  delete from public.integrantes where grupo_id = p_grupo_id and id <> all (v_manter);
end $$;
revoke all on function public.definir_integrantes_grupo(bigint, text[]) from public, anon, authenticated;
grant execute on function public.definir_integrantes_grupo(bigint, text[]) to service_role;

-- Converte o array grupos.integrantes (versão anterior), se existir, e remove a coluna.
do $$
declare
  r record;
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'grupos' and column_name = 'integrantes') then
    for r in execute 'select id, integrantes from public.grupos order by id' loop
      perform public.definir_integrantes_grupo(r.id, r.integrantes);
    end loop;
    alter table public.grupos drop column integrantes;
  end if;
end $$;
